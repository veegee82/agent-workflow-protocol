# ---------------------------------------------------------------------------
# 5. Render — structured → file artifact (backend slot)
# ---------------------------------------------------------------------------


def _render_skeleton(params: dict[str, Any]) -> tuple[str, tuple[str, ...]]:
    """Render structured data to a file.

    Params:
      - ``name``    : tool fqn
      - ``backend`` : "matplotlib_png" | "reportlab_pdf" | "markdown" |
                       "html" | "json"
      - ``inputs``  : dict[str, str] (must include 'path' or equivalent)
      - ``layout``  : backend-specific Python snippet that, given the
                       caller kwargs, produces the artifact at ``path``.
                       Optional for the simple text backends (markdown,
                       json) where a default exists.
    """
    name = params["name"]
    backend = params["backend"]
    inputs = params.get("inputs", {}) or {}
    layout = params.get("layout")
    sig = _signature(inputs)
    pkgs: tuple[str, ...] = ()

    if backend == "matplotlib_png":
        pkgs = ("matplotlib",)
        if not layout:
            raise ValueError("render(matplotlib_png) requires a 'layout' snippet")
        body = '''        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import os
'''
        body += "\n".join("        " + l for l in layout.splitlines())
        body += '''
        _size = os.path.getsize(path)
        if _size < 1000:
            return {"ok": False, "status": 500,
                    "data": {"path": path, "size_bytes": int(_size)},
                    "error": f"PNG suspiciously small ({_size} bytes)"}
        _data = {"path": path, "size_bytes": int(_size), "confidence": 1.0}
'''
    elif backend == "reportlab_pdf":
        pkgs = ("reportlab",)
        if not layout:
            raise ValueError("render(reportlab_pdf) requires a 'layout' snippet")
        body = '''        from reportlab.lib.pagesizes import letter
        from reportlab.pdfgen import canvas
        import os
        _c = canvas.Canvas(path, pagesize=letter)
'''
        body += "\n".join("        " + l for l in layout.splitlines())
        body += '''
        _c.save()
        _size = os.path.getsize(path)
        _data = {"path": path, "size_bytes": int(_size), "confidence": 1.0}
'''
    elif backend == "markdown":
        body = '''        import os
        _lines = []
'''
        if layout:
            body += "\n".join("        " + l for l in layout.splitlines())
        else:
            body += '''        _lines.append(f"# {title}")
        _lines.append("")
        if isinstance(body, str):
            _lines.append(body)
'''
        body += '''
        _text = "\\n".join(_lines) + "\\n"
        with open(path, "w", encoding="utf-8") as _fh:
            _fh.write(_text)
        _size = os.path.getsize(path)
        _data = {"path": path, "size_bytes": int(_size), "confidence": 1.0}
'''
    elif backend == "html":
        body = '''        import os
        _html = ""
'''
        if layout:
            body += "\n".join("        " + l for l in layout.splitlines())
        else:
            body += '''        _html = f"<!doctype html><html><head><title>{title}</title></head><body>{body}</body></html>"
'''
        body += '''
        with open(path, "w", encoding="utf-8") as _fh:
            _fh.write(_html)
        _size = os.path.getsize(path)
        _data = {"path": path, "size_bytes": int(_size), "confidence": 1.0}
'''
    elif backend == "json":
        body = '''        import json, os
        with open(path, "w", encoding="utf-8") as _fh:
            json.dump(value, _fh, indent=2, default=str)
        _size = os.path.getsize(path)
        _data = {"path": path, "size_bytes": int(_size), "confidence": 1.0}
'''
    else:
        raise ValueError(f"render: unknown backend {backend!r}")

    return _wrap(name, sig, body), pkgs


def _render_smoke(params: dict[str, Any]) -> str:
    return params.get("smoke_test", 'print("ARCHETYPE_OK render (no smoke supplied)")')


