# 4. Transform — structured → structured
# ---------------------------------------------------------------------------


def _transform_skeleton(params: dict[str, Any]) -> tuple[str, tuple[str, ...]]:
    """Generic structured-data transform.

    Params:
      - ``name``     : tool fqn
      - ``inputs``   : dict[str, str]
      - ``op_chain`` : Python snippet that reads kwargs, populates ``_data``
                       (must include ``_data['confidence']``)
      - ``packages`` : tuple
    """
    name = params["name"]
    inputs = params.get("inputs", {}) or {}
    op = params["op_chain"]
    pkgs = tuple(params.get("packages", ()) or ())
    sig = _signature(inputs)
    body = "        _data = {}\n" + "\n".join("        " + l for l in op.splitlines())
    return _wrap(name, sig, body), pkgs


